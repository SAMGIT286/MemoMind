export function getTransliteratedName(name, targetLang = "English") {
  if (!name || typeof name !== "string" || !name.trim()) return name || "";
  const clean = name.trim();
  const tgt = normalizeLanguageCode(targetLang);
  if (tgt === "en") return clean;

  const lower = clean.toLowerCase();
  if (KNOWN_NAME_TRANSLITERATIONS[lower] && KNOWN_NAME_TRANSLITERATIONS[lower][tgt]) {
    return KNOWN_NAME_TRANSLITERATIONS[lower][tgt];
  }

  // Check cache
  const cached = getCachedTranslation(clean, "en", tgt, "user_name");
  if (cached) return cached;

  return clean;
}

export function getTranslation(lang = "English") {
  const normName = getLanguageDisplayName(lang);
  return translations[normName] || translations.English;
}
