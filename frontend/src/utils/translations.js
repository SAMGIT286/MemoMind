// Language normalization helpers
export function normalizeLanguageCode(lang) {
  if (!lang) return "en";
  const clean = String(lang).trim().toLowerCase();
  if (clean === "mr" || clean === "marathi") return "mr";
  if (clean === "hi" || clean === "hindi") return "hi";
  return "en";
}

export function getLanguageDisplayName(code) {
  const norm = normalizeLanguageCode(code);
  if (norm === "mr") return "Marathi";
  if (norm === "hi") return "Hindi";
  return "English";
}

// In-Memory & LocalStorage Translation Cache
const CACHE_KEY = "memomind_translation_cache_v2";
const memoryCache = new Map();

// Initialize memory cache from localStorage
try {
  const saved = localStorage.getItem(CACHE_KEY);
  if (saved) {
    const parsed = JSON.parse(saved);
    Object.entries(parsed).forEach(([k, v]) => memoryCache.set(k, v));
  }
} catch {
  // Ignore localStorage read error
}

export function generateContentHash(text, sourceLang = "en", targetLang = "hi", context = "general") {
  const src = normalizeLanguageCode(sourceLang);
  const tgt = normalizeLanguageCode(targetLang);
  const ctx = (context || "general").trim().toLowerCase();
  const raw = `${(text || "").trim()}||${src}||${tgt}||${ctx}`;
  // Fast FNV-1a hash
  let hash = 2166136261;
  for (let i = 0; i < raw.length; i++) {
    hash ^= raw.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  return (hash >>> 0).toString(16);
}

export function getCachedTranslation(text, sourceLang = "en", targetLang = "hi", context = "general") {
  if (!text || !text.trim()) return text;
  const src = normalizeLanguageCode(sourceLang);
  const tgt = normalizeLanguageCode(targetLang);
  if (src === tgt) return text;

  const hashKey = generateContentHash(text, src, tgt, context);
  if (memoryCache.has(hashKey)) return memoryCache.get(hashKey);

  // Check static dictionary if context is "ui"
  const tgtName = getLanguageDisplayName(tgt);
  const dict = translations[tgtName] || {};
  if (dict[text]) return dict[text];

  return null;
}

export function setCachedTranslation(text, sourceLang = "en", targetLang = "hi", context = "general", translatedText) {
  if (!text || !translatedText) return;
  const src = normalizeLanguageCode(sourceLang);
  const tgt = normalizeLanguageCode(targetLang);
  const hashKey = generateContentHash(text, src, tgt, context);
  memoryCache.set(hashKey, translatedText);

  // Persist asynchronously to localStorage
  try {
    const obj = {};
    // Keep at most 500 entries in localStorage
    const entries = Array.from(memoryCache.entries()).slice(-500);
    entries.forEach(([k, v]) => { obj[k] = v; });
    localStorage.setItem(CACHE_KEY, JSON.stringify(obj));
  } catch {
    // Ignore quota issues
  }
}

export function hydrateTranslationCache(translationsMap, targetLang = "hi") {
  if (!translationsMap || typeof translationsMap !== "object") return;
  const tgt = normalizeLanguageCode(targetLang);
  Object.entries(translationsMap).forEach(([key, value]) => {
    if (typeof value === "string" && value.trim()) {
      if (key.startsWith("hash:")) {
        memoryCache.set(key.replace("hash:", ""), value);
      } else {
        const hashKey = generateContentHash(key, "en", tgt, "ui");
        memoryCache.set(hashKey, value);
      }
    }
  });
}

// Language Detection (Devanagari / Latin script and grammar particles)
const MARATHI_REGEX = /\b(आहे|नाही|आहेत|नाहीत|झाले|झाला|झाली|घ्या|द्या|करा|करावे|बघ|पहा|उद्या|काल|आज|सकाळी|दुपारी|संध्याकाळी|रात्री|औषध|गोळी|भेट|नाव|माझे|माझी|माझा|तुमचे|तुमची|तुमचा|च्या|साठी|मध्ये|वरून|कडून|ला|स)\b|[ळऱ]/;
const HINDI_REGEX = /\b(है|हैं|नहीं|हुआ|हुई|हुए|लो|दो|कीजिए|करना|देख|कल|आज|सुबह|दोपहर|शाम|रात|दवा|दवाइयाँ|गोली|मुलाकात|नाम|मेरा|मेरी|मेरे|आपका|आपकी|आपके|के|की|का|लिए|में|से|पर|को|था|थी|थे|हूँ)\b/;

export function detectSourceLanguage(text, defaultLang = "en") {
  if (!text || typeof text !== "string" || !text.trim()) {
    return normalizeLanguageCode(defaultLang);
  }
  const clean = text.trim();
  const hasDevanagari = /[\u0900-\u097F]/.test(clean);
  const hasLatin = /[a-zA-Z]/.test(clean);

  if (!hasDevanagari && hasLatin) return "en";

  if (hasDevanagari) {
    if (MARATHI_REGEX.test(clean)) return "mr";
    if (HINDI_REGEX.test(clean)) return "hi";
    const normDef = normalizeLanguageCode(defaultLang);
    if (normDef === "mr" || normDef === "hi") return normDef;
    return "hi";
  }

  return normalizeLanguageCode(defaultLang);
}

